export type TKey = keyof typeof dict;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string; tArr: (k: TKey) => string[] }>({
  lang: "sl",
  setLang: () => {},
  t: (k) => k,
  tArr: () => [],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("sl");
  useEffect(() => {
    const saved = typeof window !== "undefined" ? (localStorage.getItem("kz_lang") as Lang | null) : null;
    if (saved === "sl" || saved === "en") setLangState(saved);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("kz_lang", l);
  };
  const t = (k: TKey) => {
    const v = (dict as any)[k]?.[lang];
    return typeof v === "string" ? v : k;
  };
  const tArr = (k: TKey) => {
    const v = (dict as any)[k]?.[lang];
    return Array.isArray(v) ? v : [];
  };
  return <Ctx.Provider value={{ lang, setLang, t, tArr }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
