function statusVariant(s) {
  if (s === "delivered") return "default";
  if (s === "sent") return "secondary";
  if (s === "pending" || s === "queued") return "outline";
  if (s === "failed" || s === "dlq" || s === "bounced" || s === "complained") return "destructive";
  return "outline";
}
